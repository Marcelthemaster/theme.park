def glyph(font, ch):
    rows = [r for r in font[ch].strip('\n').split('\n')]
    w = max(len(r) for r in rows)
    a = np.zeros((len(rows), w), bool)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            a[y, x] = c == '#'
    return a


def text_mask(font, text, tracking=2, space=None):
    gl = [glyph(font, ch) for ch in text]
    h = gl[0].shape[0]
    widths = []
    for ch, g in zip(text, gl):
        widths.append(space if (ch == ' ' and space is not None) else g.shape[1])
    W = sum(widths) + tracking * (len(gl) - 1)
    m = np.zeros((h, W), bool)
    x = 0
    for ch, g, w in zip(text, gl, widths):
        if ch != ' ':
            m[:, x:x + g.shape[1]] = g
        x += w + tracking
    return m


def styled(mask, face, top=None, bottom=None, edge=('iron', 0), shadow=('iron', 1), pad=2):
    """Render a text mask with a face ramp, 1px outline and a 1px drop shadow."""
    h, w = mask.shape
    c = Canvas(w + 2 * pad, h + 2 * pad + 1)
    m = np.zeros((c.h, c.w), bool)
    m[pad:pad + h, pad:pad + w] = mask
    sh = np.zeros_like(m)
    sh[1:] = m[:-1]
    sh &= ~m
    c.put(sh, col(*shadow))
    Y = np.arange(c.h)[:, None].repeat(c.w, 1) - pad
    if callable(face):
        face(c, m, Y)
    else:
        c.put(m, col(*face))
    if top:
        c.put(m & (Y == 0), col(*top))
    if bottom:
        c.put(m & (Y == h - 1), col(*bottom))
    c.put(outline(m | sh), col(*edge))
    return c
