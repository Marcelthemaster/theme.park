"""Final packaging run: docs -> QA checks -> QA report -> SHA256SUMS -> ZIP -> verification.

    python3 finalize.py

Two-pass: the QA report contains the package verification of pass 1; the archive is then rebuilt with
the final report and verified again (pass 2). The pass-2 result is written next to the ZIP to
PACKAGE_VERIFICATION.txt (it cannot be inside the archive it describes).
"""
from __future__ import annotations

import datetime
import hashlib
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))
PKG = os.path.join(ROOT, 'package', 'AVARNETH_Complete_Branding_Startup_V1.0')
WORK = os.path.join(ROOT, 'work')


EVIDENCE_FILES = (
    '05_Unity_Integration/Runtime/AvarnethStartupAnimation.cs',
    '05_Unity_Integration/Runtime/AvarnethStartupTimelineMath.cs',
    '05_Unity_Integration/Runtime/Eckertengineering.Avarneth.Startup.asmdef',
    '05_Unity_Integration/Editor/AvarnethStartupInstaller.cs',
    '05_Unity_Integration/Editor/Eckertengineering.Avarneth.Startup.Editor.asmdef',
    '05_Unity_Integration/README_UNITY_FOLDER.txt',
    '05_Unity_Integration/Importable_Assets/Animation_Timeline.json',
    '07_Documentation/UNITY_INSTALLATION.md',
    '07_Documentation/PLAYER_SETTINGS.md',
)


def shipped_section():
    """Generated section 9 of the evidence copy: the files as they are actually shipped."""
    rows = []
    for rel in EVIDENCE_FILES:
        with open(os.path.join(PKG, rel), 'rb') as f:
            data = f.read()
        lines = data.count(b'\n')
        rows.append(f'| `{rel}` | {lines} | `{hashlib.sha256(data).hexdigest()}` |')
    return '\n'.join([
        '',
        '## 9. Shipped files (generated by `tools/finalize.py` at packaging time)',
        '',
        'Sections 1-8 are the working log of the integration rounds. The file tables in sections 1 and 7.3 and the',
        'line numbers quoted with compiler messages (e.g. CS0436) describe the files at that point in time; the',
        'limitation "veil seam still present" in section 7.4 is resolved by section 8 (full-screen veil). The C# vs.',
        'Python cross-check in section 8 was run on the revision-2 timeline; the builds, the math self-test, the API',
        'check and the cross-check are re-run against the shipped revision-3 files on every packaging run and their',
        'current results are in `QA_REPORT.md` (sections 3 "Animationsprüfung" and 4 "Unity-Integrationsprüfung").',
        '',
        '| File | Lines | SHA-256 |',
        '|---|---|---|',
        *rows,
        '',
    ])


def run(*args):
    print('$', ' '.join(args), flush=True)
    subprocess.run(['python3', *args], cwd=HERE, check=True)


def main():
    run('make_docs.py')
    with open(os.path.join(WORK, 'unity_compile_evidence.md')) as f:
        evidence = f.read().rstrip('\n') + '\n'
    with open(os.path.join(PKG, '07_Documentation', 'UNITY_COMPILE_EVIDENCE.md'), 'w') as f:
        f.write(evidence + shipped_section())
    # copy the current generator sources into the package (Source_Files/generator)
    run('build_all.py', 'sources')
    run('qa.py', 'checks')
    run('qa_report.py')                 # pass 1 report (package section: previous verification if present)
    run('qa.py', 'package')             # sums + zip + verify (pass 1)
    run('qa_report.py')                 # report now includes the pass-1 package verification
    run('qa.py', 'package')             # final sums + zip + verify (pass 2)
    pv = json.load(open(os.path.join(WORK, 'package_verification.json')))
    lines = [f'AVARNETH_Complete_Branding_Startup_V1.0.zip - package verification ({datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")})',
             f'zip size: {pv["zip_size"]} bytes', f'zip sha256: {pv["zip_sha256"]}', '']
    for k in ('zip_test', 'complete', 'readable', 'no_zero_bytes', 'sha256_check', 'docs'):
        ok, txt = pv[k]
        lines.append(f'{"PASS" if ok else "FAIL"}  {k}: {txt}')
    with open(os.path.join(ROOT, 'package', 'PACKAGE_VERIFICATION.txt'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
